import fs from 'node:fs';
import path from 'node:path';

/**
 * Minimal OpenAPI -> MCP tool generator.
 *
 * Input: OpenAPI 3.x JSON (default: tools/mcp-server/openapi.json)
 * Output: tools/mcp-server/generated-tools.js
 *
 * This generator is intentionally conservative:
 * - Generates tools for all HTTP operations found in the OpenAPI spec.
 * - Only supports JSON request bodies and query/path params.
 * - Produces a JS module exporting `registerGeneratedTools(server, helpers)`.
 */

const repoRoot = process.cwd();
const openapiPath = process.env.SF_OPENAPI_PATH
  ? path.resolve(repoRoot, process.env.SF_OPENAPI_PATH)
  : path.resolve(repoRoot, 'tools/mcp-server/openapi.json');

const outPath = path.resolve(repoRoot, 'tools/mcp-server/generated-tools.js');

function die(msg) {
  console.error(`[mcp-gen] ${msg}`);
  process.exit(1);
}

function readJson(p) {
  if (!fs.existsSync(p)) die(`OpenAPI file not found: ${p}`);
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function toToolName(method, rawPath) {
  const cleaned = rawPath
    .replace(/^\//, '')
    .replace(/\//g, '_')
    .replace(/[{}]/g, '')
    .replace(/[^a-zA-Z0-9_]/g, '_');
  return `${method.toLowerCase()}_${cleaned}`;
}

function schemaToZod(schema) {
  // Very small subset; fallback to z.any()
  if (!schema || typeof schema !== 'object') return 'z.any()';
  if (schema.$ref) return 'z.any()';

  switch (schema.type) {
    case 'string':
      return 'z.string()';
    case 'integer':
      return 'z.number().int()';
    case 'number':
      return 'z.number()';
    case 'boolean':
      return 'z.boolean()';
    case 'array':
      return `z.array(${schemaToZod(schema.items)})`;
    case 'object': {
      const props = schema.properties || {};
      const required = new Set(schema.required || []);
      const entries = Object.entries(props).map(([k, v]) => {
        const base = schemaToZod(v);
        return `  ${JSON.stringify(k)}: ${required.has(k) ? base : `${base}.optional()`}`;
      });
      return `z.object({\n${entries.join(',\n')}\n})`;
    }
    default:
      return 'z.any()';
  }
}

function pickJsonRequestSchema(op) {
  const rb = op.requestBody;
  if (!rb || !rb.content) return null;
  const json = rb.content['application/json'];
  if (!json || !json.schema) return null;
  return json.schema;
}

function buildInputSchema(op) {
  const params = Array.isArray(op.parameters) ? op.parameters : [];
  const shape = {};

  for (const p of params) {
    if (!p || !p.name) continue;
    const zod = schemaToZod(p.schema);
    shape[p.name] = p.required ? zod : `${zod}.optional()`;
  }

  const bodySchema = pickJsonRequestSchema(op);
  if (bodySchema) {
    shape.body = schemaToZod(bodySchema);
  }

  const lines = Object.entries(shape).map(([k, v]) => `      ${k}: ${v},`);
  return `{
${lines.join('\n')}
    }`;
}

function shouldGenerate(_op) {
  // Intentionally generate tools for all operations.
  // (Previously gated by `x-mcp: true` or tag `mcp`.)
  return true;
}

const spec = readJson(openapiPath);
if (!spec.paths) die('OpenAPI spec missing paths');

const ops = [];
for (const [p, methods] of Object.entries(spec.paths)) {
  for (const [m, op] of Object.entries(methods)) {
    const method = m.toLowerCase();
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
    if (!op || typeof op !== 'object') continue;
    if (!shouldGenerate(op)) continue;

    const toolName = op.operationId || toToolName(method, p);
    const description = op.summary || op.description || `${method.toUpperCase()} ${p}`;
    const inputSchema = buildInputSchema(op);

    ops.push({ toolName, description, method, path: p, inputSchema });
  }
}

const header = `// AUTO-GENERATED FILE. DO NOT EDIT.
// Generated by tools/mcp-server/generate-tools-from-openapi.mjs

const { z } = require('zod');

/**
 * @param {import('@modelcontextprotocol/sdk/server/mcp.js').McpServer} server
 * @param {{ sfRequest: (method: string, url: string, options: any) => Promise<any>, safeJsonStringify: (v:any)=>string, SF_BACKEND: string }} helpers
 */
function registerGeneratedTools(server, helpers) {
  const { sfRequest, safeJsonStringify, SF_BACKEND } = helpers;

`;

const body = ops
  .map((op) => {
    const urlExpr = '`' + '${SF_BACKEND}' + op.path.replace(/{/g, '${') + '`';

    // Build query string from non-path params (best-effort)
    const queryBuild = `
      const query = new URLSearchParams();
      for (const [k, v] of Object.entries(args)) {
        if (v === undefined || v === null) continue;
        if (k === 'body') continue;
        // skip path params (already interpolated)
        if (${JSON.stringify(op.path)}.includes('{' + k + '}')) continue;
        query.set(k, String(v));
      }
      const url = ${urlExpr} + (query.toString() ? ('?' + query.toString()) : '');
`;

    const call = `
      const resp = await sfRequest(${JSON.stringify(op.method.toUpperCase())}, url, {
        headers: { 'Content-Type': 'application/json' },
        data: args.body,
      });

      if (resp.status >= 200 && resp.status < 300) {
        return { content: [{ type: 'text', text: safeJsonStringify(resp.data) }] };
      }
      return { isError: true, content: [{ type: 'text', text: 'Backend error (' + resp.status + '): ' + safeJsonStringify(resp.data) }] };
`;

    return `  server.tool(
    ${JSON.stringify(op.toolName)},
    ${JSON.stringify(op.description)},
    ${op.inputSchema},
    async (args) => {
${queryBuild}
${call}
    }
  );
`;
  })
  .join('\n');

const footer = `}

module.exports = { registerGeneratedTools };
`;

fs.writeFileSync(outPath, header + body + footer, 'utf8');
console.log(`[mcp-gen] Wrote ${outPath} with ${ops.length} tools`);
